@pytest.mark.parametrize("symlink_parent", [False, True])
def test_export_inventory_rejects_symlinked_payload(tmp_path, symlink_parent):
    actual = tmp_path / "actual/module.py"
    actual.parent.mkdir()
    actual.write_text("pass\n")
    if symlink_parent:
        (tmp_path / "src").symlink_to(actual.parent, target_is_directory=True)
    else:
        (tmp_path / "src").mkdir()
        (tmp_path / "src/module.py").symlink_to(actual)
    _write_release_receipt(tmp_path, ["src/module.py"])
    with pytest.raises(ValueError, match="symlink"):
        layout.candidate_paths(tmp_path)


def test_export_inventory_accepts_actual_exporter_rows(tmp_path):
    from microcosm_core import release_export

    source = tmp_path / "src/module.py"
    source.parent.mkdir()
    source.write_text("pass\n")
    _write_release_receipt(tmp_path, ["src/module.py"])
    receipt_path = tmp_path / layout.RELEASE_RECEIPT
    receipt = json.loads(receipt_path.read_text())
    rows = release_export._artifact_inventory_for_paths(tmp_path, ["src/module.py"])
