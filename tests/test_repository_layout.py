def test_index_sees_staged_additions_and_deletions_ignores_local_output(tmp_path):
    def git(*args):
        return subprocess.run(["git", "-C", str(tmp_path), *args], check=True, capture_output=True)
    git("init", "-q")
    (tmp_path / ".gitignore").write_text("scratch/\n")
    (tmp_path / "scratch").mkdir()
    (tmp_path / "scratch/ignored.py").write_text("ignored")
    (tmp_path / "untracked.py").write_text("untracked")
    (tmp_path / "scripts").mkdir()
    bad = tmp_path / "scripts/misplaced.py"
    bad.write_text("staged")
    git("add", ".gitignore", "scripts/misplaced.py")
    paths = layout.candidate_paths(tmp_path)
    assert paths == [".gitignore", "scripts/misplaced.py"]
    assert layout.violations(POLICY["required_paths"] + paths, POLICY)
    git("rm", "--cached", "scripts/misplaced.py")
    assert "scripts/misplaced.py" not in layout.candidate_paths(tmp_path)


def test_shipped_tree_fallback(tmp_path):
    (tmp_path / "scripts").mkdir()
    (tmp_path / "scripts/bad.py").write_text("pass")
    assert layout.candidate_paths(tmp_path) == ["scripts/bad.py"]


def _write_release_receipt(root: Path, paths: list[str]) -> None:
    rows = []
    for path in paths:
        candidate = root / path
        data = candidate.read_bytes() if candidate.is_file() else b""
        rows.append({
            "path": path,
            "role": "test",
            "size_bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
            "git_mode": "100644",
        })
    payload_hash = hashlib.sha256(
        json.dumps(rows, ensure_ascii=True, sort_keys=True).encode("utf-8")
    ).hexdigest()
    receipt = {
        "schema_version": "microcosm_release_export_receipt_v1",
        "status": "pass",
        "artifact": {
            "mode": "generated_standalone_folder",
            "file_count": len(paths),
            "artifact_payload_hash_sha256": payload_hash,
        },
        "inventory_receipt": {
            "status": "pass",
            "manifest_policy": "allowlisted_public_tree",
            "file_count": len(paths),
            "files": rows,
        },
    }
    receipt_path = root / layout.RELEASE_RECEIPT
    receipt_path.parent.mkdir(parents=True, exist_ok=True)
    receipt_path.write_text(json.dumps(receipt))


def test_export_inventory_ignores_only_runtime_bytecode(tmp_path):
    source = tmp_path / "src/module.py"
    source.parent.mkdir()
    source.write_text("pass\n")
    _write_release_receipt(tmp_path, ["src/module.py"])
    cache = tmp_path / "src/__pycache__/module.cpython-312.pyc"
    cache.parent.mkdir()
    cache.write_bytes(b"runtime cache")
    misplaced = tmp_path / "docs/bad.py"
    misplaced.parent.mkdir()
    misplaced.write_text("pass\n")

    paths = layout.candidate_paths(tmp_path)
    assert "src/module.py" in paths
    assert "src/__pycache__/module.cpython-312.pyc" not in paths
    assert "docs/bad.py" in paths
    assert any(
        error.startswith("docs/bad.py:")
        for error in layout.violations(POLICY["required_paths"] + paths, POLICY)
    )


def test_export_inventory_cannot_hide_shipped_or_unattested_bytecode(tmp_path):
    cache = tmp_path / "src/__pycache__/module.cpython-312.pyc"
    cache.parent.mkdir(parents=True)
    cache.write_bytes(b"shipped cache")
    _write_release_receipt(tmp_path, ["src/__pycache__/module.cpython-312.pyc"])
    paths = layout.candidate_paths(tmp_path)
    assert cache.relative_to(tmp_path).as_posix() in paths
    assert any("generated bytecode" in error for error in layout.violations(paths, POLICY))

    (tmp_path / layout.RELEASE_RECEIPT).unlink()
    assert cache.relative_to(tmp_path).as_posix() in layout.candidate_paths(tmp_path)


def test_export_inventory_fails_when_stale_or_malformed(tmp_path):
    _write_release_receipt(tmp_path, ["src/missing.py"])
    with pytest.raises(ValueError, match="listed files missing"):
        layout.candidate_paths(tmp_path)

    _write_release_receipt(tmp_path, ["../outside.py"])
    with pytest.raises(ValueError, match="invalid inventory path"):
        layout.candidate_paths(tmp_path)


@pytest.mark.parametrize(
    "change",
    ["empty", "count", "aggregate_hash", "missing_size", "invalid_digest", "missing_mode", "invalid_mode", "nonfinite", "duplicate"],
)
def test_export_inventory_rejects_corrupt_metadata(tmp_path, change):
    source = tmp_path / "src/module.py"
    source.parent.mkdir()
    source.write_text("pass\n")
    _write_release_receipt(tmp_path, ["src/module.py"])
    receipt_path = tmp_path / layout.RELEASE_RECEIPT
    receipt = json.loads(receipt_path.read_text())
    inventory = receipt["inventory_receipt"]
    artifact = receipt["artifact"]
    if change == "empty":
        inventory["files"] = []
        inventory["file_count"] = artifact["file_count"] = 0
    elif change == "count":
        inventory["file_count"] = 2
    elif change == "aggregate_hash":
        artifact["artifact_payload_hash_sha256"] = "0" * 64
    elif change == "missing_size":
        del inventory["files"][0]["size_bytes"]
    elif change == "invalid_digest":
        inventory["files"][0]["sha256"] = "not-a-digest"
    elif change == "missing_mode":
        del inventory["files"][0]["git_mode"]
    elif change == "invalid_mode":
        inventory["files"][0]["git_mode"] = "120000"
    elif change == "nonfinite":
        artifact["unexpected"] = float("nan")
    else:
        inventory["files"].append(dict(inventory["files"][0]))
        inventory["file_count"] = artifact["file_count"] = 2
    receipt_path.write_text(json.dumps(receipt))
    with pytest.raises(ValueError, match="invalid release inventory|inventory|invalid JSON"):
        layout.candidate_paths(tmp_path)


